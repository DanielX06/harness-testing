"""Score the true device and deliberately wrong versions of it on one grid, closed loop.

    python check_grid.py M                  # writes monitor_check.json
    python check_grid.py B --out other.json --workers 4

The set matches selection_check.json: the truth (must score 0), the flat prediction (must score 1),
REGF1 with an ideal current loop, and the true structure with one parameter off (wdrp x0.8,
Qdrp x0.8, Tpm x2, KPv x0.7). A new grid should charge each error roughly what grid B charges, so
its score moves for the same reasons B's does.
"""
import argparse
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCORER = os.path.join(os.path.dirname(HERE), "scorer")
sys.path.insert(0, SCORER)

VARIANTS = [("truth", "full", None), ("flat", None, None), ("ideal_loop", "ideal", None),
            ("wdrp_x0.8", "full", {"wdrp": 0.8}), ("Qdrp_x0.8", "full", {"Qdrp": 0.8}),
            ("Tpm_x2", "full", {"Tpm": 2.0}), ("KPv_x0.7", "full", {"KPv": 0.7})]
KEEP = ("score", "td", "fr", "par", "td_runs", "failures")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("grid", help="grid letter, e.g. M for test_cases/grid_M")
    ap.add_argument("--out", default=None, help="default: monitor_check.json for M, <grid>_check.json otherwise")
    ap.add_argument("--workers", type=int, default=None)
    a = ap.parse_args()

    import andes
    from score import score_submission
    from truth import regf1_spec as R
    andes.config_logger(stream_level=40)

    name = f"grid_{a.grid}"
    path = os.path.join(HERE, name)
    key = json.load(open(os.path.join(path, "holdout", "answer_key.json")))
    base = json.load(open(os.path.join(SCORER, "config_min.json")))
    cfg = {k: v for k, v in base.items() if k not in ("_note", "grids")}
    cfg["grids"] = [{"name": name, "role": "monitor", "format": "kundur_family_v1", "path": path}]
    out = a.out or os.path.join(HERE, "monitor_check.json" if a.grid == "M" else f"{a.grid}_check.json")

    tmp = tempfile.mkdtemp(prefix="check_grid_")
    cpath = os.path.join(tmp, "config.json")
    json.dump(cfg, open(cpath, "w"))
    rows = {}
    for label, inner, scale in VARIANTS:
        if inner is None:
            sub = os.path.join(SCORER, "baselines", "flat.json")
        else:
            sub = os.path.join(tmp, f"{label}.json")
            json.dump(R.spec(key["params_used"], inner, Sn=float(key["device_rating_MVA"]), scale=scale),
                      open(sub, "w"), indent=1)
        _, priv = score_submission(sub, cpath, n_workers=a.workers)
        g = priv["grids"][name]
        rows[label] = {k: g[k] for k in KEEP if k in g}
        print(f"{label:11s} score {g['score']:.4f}  td {g['td']:.4f}  fr {g['fr']:.4f}  par {g['par']:.4f}  "
              f"({priv['wall_seconds']} s)", flush=True)
    note = (f"Closed-loop scores of the true REGF1 written as a submission with one parameter changed, scored on "
            f"{name} alone with config_min.json's settings. Generated by check_grid.py.")
    json.dump({"_note": note, name: rows}, open(out, "w"), indent=1)
    print("wrote", out)


if __name__ == "__main__":
    main()

"""Score the true device and deliberately wrong versions of it on one grid, closed loop.

    python test_cases/score_wrong_models_on_grid.py M                  # writes test_cases/monitor_check.json
    python test_cases/score_wrong_models_on_grid.py B --out other.json --workers 4

The versions are the truth (must score 0), the flat prediction (must score 1), the device with an ideal current
loop, and the true structure with one parameter off. A new grid should charge each error roughly what grid B
charges, so its score moves for the same reasons B's does. The grid's device comes from its answer key, and its
wrong versions from WRONG_VERSIONS below.
"""
import argparse
import json
import os
import sys
import tempfile

TEST_CASES_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(TEST_CASES_DIR))         # the repository root
from common.project_paths import MIN_SCORER_CONFIG, SCORER_DIR  # noqa: E402

# (label, inner loop, {parameter: factor}) per device model; an inner loop of None means the flat prediction
WRONG_VERSIONS = {
    "REGF1": [("truth", "full", None), ("flat", None, None), ("ideal_loop", "ideal", None),
              ("wdrp_x0.8", "full", {"wdrp": 0.8}), ("Qdrp_x0.8", "full", {"Qdrp": 0.8}),
              ("Tpm_x2", "full", {"Tpm": 2.0}), ("KPv_x0.7", "full", {"KPv": 0.7})],
}
KEPT_FIELDS = ("score", "td", "fr", "par", "td_runs", "failures")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("grid", help="grid letter, e.g. M for test_cases/grid_M")
    parser.add_argument("--out", default=None, help="default: monitor_check.json for M, grid_<letter>_check.json otherwise")
    parser.add_argument("--workers", type=int, default=None, help="ANDES simulations at once")
    options = parser.parse_args()

    import andes
    from scorer.score_submission import SubmissionScorer
    from scorer.truth import TRUTH_SPEC_BUILDERS
    andes.config_logger(stream_level=40)

    name = f"grid_{options.grid}"
    grid_dir = os.path.join(TEST_CASES_DIR, name)
    with open(os.path.join(grid_dir, "holdout", "answer_key.json")) as file:
        answer_key = json.load(file)
    with open(os.path.join(grid_dir, "holdout", "case.json")) as file:
        grid_format = json.load(file)["format"]
    device = answer_key["device"]
    if device not in WRONG_VERSIONS:
        raise SystemExit(f"no wrong versions listed for {device}; add them to WRONG_VERSIONS")
    with open(MIN_SCORER_CONFIG) as file:
        config = {key: value for key, value in json.load(file).items() if key not in ("_note", "grids")}
    config["grids"] = [{"name": name, "role": "monitor", "format": grid_format, "path": grid_dir}]
    out = options.out or os.path.join(TEST_CASES_DIR, "monitor_check.json" if options.grid == "M" else f"{name}_check.json")

    scratch = tempfile.mkdtemp(prefix="wrong_models_")
    config_path = os.path.join(scratch, "config.json")
    with open(config_path, "w") as file:
        json.dump(config, file)
    scorer = SubmissionScorer(config_path, worker_count=options.workers)
    rows = {}
    for label, inner_loop, parameter_scale in WRONG_VERSIONS[device]:
        if inner_loop is None:
            submission_path = os.path.join(SCORER_DIR, "baselines", "flat.json")
        else:
            submission_path = os.path.join(scratch, f"{label}.json")
            with open(submission_path, "w") as file:
                json.dump(TRUTH_SPEC_BUILDERS[device](answer_key["params_used"], inner_loop=inner_loop,
                                                      rating_mva=float(answer_key["device_rating_MVA"]),
                                                      parameter_scale=parameter_scale), file, indent=1)
        report = scorer.score(submission_path)
        grid = report.private["grids"][name]
        rows[label] = {key: grid[key] for key in KEPT_FIELDS if key in grid}
        print(f"{label:11s} score {grid['score']:.4f}  td {grid['td']:.4f}  fr {grid['fr']:.4f}  par {grid['par']:.4f}  "
              f"({report.private['wall_seconds']} s)", flush=True)
    note = (f"Closed-loop scores of the true {device} written as a submission with one parameter changed, scored on "
            f"{name} alone with config_min.json's settings. Generated by score_wrong_models_on_grid.py.")
    with open(out, "w") as file:
        json.dump({"_note": note, name: rows}, file, indent=1)
    print("wrote", out)


if __name__ == "__main__":
    main()
